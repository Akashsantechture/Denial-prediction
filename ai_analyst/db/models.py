import uuid

from datetime import datetime, timezone

from sqlalchemy import (
    Column,
    String,
    Text,
    Integer,
    DateTime,
    JSON,
    ForeignKey,
)

from sqlalchemy.orm import relationship

from .database import Base


# ============================================================
# ANALYST SESSIONS
# ============================================================

class AnalystSession(Base):

    __tablename__ = "analyst_sessions"

    session_id = Column(
        String(36),
        primary_key=True,
    )

    # XGBoost / prediction model version
    model_version = Column(
        String(100),
        nullable=True,
    )

    # Gemini / LLM model used for the conversation
    llm_model = Column(
        String(150),
        nullable=True,
    )

    # active / completed / deleted / error
    status = Column(
        String(30),
        nullable=False,
        default="active",
    )

    created_at = Column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
    )

    updated_at = Column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
        onupdate=lambda: datetime.now(timezone.utc),
    )

    # --------------------------------------------------------
    # Relationships
    # --------------------------------------------------------

    messages = relationship(
        "AnalystMessage",
        back_populates="session",
        cascade="all, delete-orphan",
    )

    claim_intelligence = relationship(
        "AnalystClaimIntelligence",
        back_populates="session",
        uselist=False,
        cascade="all, delete-orphan",
    )


# ============================================================
# CLAIM INTELLIGENCE
# ============================================================

class AnalystClaimIntelligence(Base):

    __tablename__ = "analyst_claim_intelligence"

    session_id = Column(
        String(36),
        ForeignKey(
            "analyst_sessions.session_id",
            ondelete="CASCADE",
        ),
        primary_key=True,
    )

    # --------------------------------------------------------
    # Sanitized evidence generated by the prediction service.
    #
    # Example:
    #
    # {
    #     "denial_probability_pct": 83,
    #     "risk_level": "HIGH",
    #     "explanation": {
    #         "top_drivers": [...],
    #         "supporting_factors": [...],
    #         "interactions": [...]
    #     }
    # }
    #
    # Keep this as Claim Intelligence rather than blindly
    # storing raw claim/PHI data.
    # --------------------------------------------------------

    evidence = Column(
        JSON,
        nullable=False,
    )

    created_at = Column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
    )

    updated_at = Column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
        onupdate=lambda: datetime.now(timezone.utc),
    )

    # --------------------------------------------------------
    # Relationship
    # --------------------------------------------------------

    session = relationship(
        "AnalystSession",
        back_populates="claim_intelligence",
    )


# ============================================================
# ANALYST MESSAGES
# ============================================================

class AnalystMessage(Base):

    __tablename__ = "analyst_messages"

    id = Column(
        String(36),
        primary_key=True,
        default=lambda: str(uuid.uuid4()),
    )

    session_id = Column(
        String(36),
        ForeignKey(
            "analyst_sessions.session_id",
            ondelete="CASCADE",
        ),
        nullable=False,
        index=True,
    )

    # user / assistant / system
    role = Column(
        String(30),
        nullable=False,
    )

    # Actual conversational message
    content = Column(
        Text,
        nullable=False,
    )

    created_at = Column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
    )

    # --------------------------------------------------------
    # Relationship
    # --------------------------------------------------------

    session = relationship(
        "AnalystSession",
        back_populates="messages",
    )


# ============================================================
# ANALYST REQUEST / AUDIT LOG
# ============================================================

class AnalystRequestLog(Base):

    __tablename__ = "analyst_request_logs"

    request_id = Column(
        String(36),
        primary_key=True,
        default=lambda: str(uuid.uuid4()),
    )

    session_id = Column(
        String(36),
        nullable=True,
        index=True,
    )

    # Example:
    # /analyst/session
    # /analyst/chat
    # /analyst/session/{session_id}
    endpoint = Column(
        String(150),
        nullable=False,
    )

    # success / error / timeout
    status = Column(
        String(30),
        nullable=False,
    )

    # API/LLM processing time
    latency_ms = Column(
        Integer,
        nullable=True,
    )

    # Gemini model
    llm_model = Column(
        String(150),
        nullable=True,
    )

    # Error details if request failed
    error_message = Column(
        Text,
        nullable=True,
    )

    # Additional non-sensitive metadata
    #
    # Example:
    #
    # {
    #     "model_version": "behavioral_xgboost_v1.5",
    #     "risk_level": "HIGH",
    #     "http_status": 200
    # }
    #
    # Do NOT put raw PHI here.
    metadata_json = Column(
        JSON,
        nullable=True,
    )

    created_at = Column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
    )